// Helpers shared by the schema generator modules (not bundled; run with `node src/features/schemas/tools/build-schemas.mjs`).
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');

/** Registries of the bundled vanilla data versions (newest first). */
export function loadRegistries() {
  const out = [];
  for (const v of ['26.3', '1.21.11', '1.21.1']) {
    const file = path.join(ROOT, 'resources/data', `${v}.json.gz`);
    const d = JSON.parse(zlib.gunzipSync(fs.readFileSync(file)).toString('utf8'));
    out.push({ version: v, registries: d.registries });
  }
  return out;
}

let REGS = null;
/** Union (sorted) of the ids of a registry across every bundled version, plus `extra`. */
export function reg(name, extra = []) {
  REGS ??= loadRegistries();
  const set = new Set(extra);
  for (const { registries } of REGS) for (const id of registries[name] ?? []) set.add(String(id).replace(/^minecraft:/, ''));
  return [...set].sort();
}

/** Plain description + markdown description (backticks kept in markdown only). */
export function md(text, schema = {}) {
  return { ...schema, description: text.replace(/`/g, '').replace(/\*\*/g, ''), markdownDescription: text };
}
export const desc = md;

export const ref = (name) => ({ $ref: `#/definitions/${name}` });
export const cref = (name) => ({ $ref: `common.json#/definitions/${name}` });
export const compRef = (name) => ({ $ref: `item-components.json#/definitions/${name}` });

export const RL = '^(?:[a-z0-9_.-]+:)?[a-z0-9_./-]+$';
export const RL_OR_TAG = '^#?(?:[a-z0-9_.-]+:)?[a-z0-9_./-]+$';
export const TAG = '^#(?:[a-z0-9_.-]+:)?[a-z0-9_./-]+$';
/** A namespaced id outside the minecraft namespace (mod / loader types). */
export const FOREIGN = '^(?!minecraft:)[a-z0-9_.-]+:[a-z0-9_./-]+$';

/**
 * A "type" field accepting the known vanilla ids (with or without `minecraft:`) or any id of another namespace
 * (mod types). Completion offers the namespaced vanilla ids.
 */
export function typeField(ids, text, opts = {}) {
  const list = [...new Set(ids)].sort();
  const s = {
    type: 'string',
    anyOf: [
      { enum: list.map((t) => `minecraft:${t}`) },
      { pattern: `^(?:${list.map(escapeRe).join('|')})$` },
      { pattern: FOREIGN },
    ],
  };
  if (opts.enumDescriptions) s.anyOf[0].markdownEnumDescriptions = list.map((t) => opts.enumDescriptions[t] ?? '');
  return md(text, s);
}

/** A string enum accepting values with or without the `minecraft:` prefix. */
export function mcEnum(values, text) {
  return md(text, {
    type: 'string',
    anyOf: [{ enum: values.map((v) => `minecraft:${v}`) }, { enum: values }],
  });
}

export function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
}

/**
 * Discriminated union on one or more keys ("type", legacy "condition"/"function"...). Each case becomes an
 * if/then so VS Code shows the right properties and good error messages; unknown types are left unconstrained.
 */
export function dispatch(keys, cases) {
  const allOf = [];
  for (const [name, then] of Object.entries(cases)) {
    const values = name.includes(':') ? [name] : [`minecraft:${name}`, name];
    for (const k of keys) {
      allOf.push({ if: { properties: { [k]: { enum: values } }, required: [k] }, then });
    }
  }
  return allOf;
}

/** Object schema helper. */
export function obj(properties, extra = {}) {
  return { type: 'object', properties, ...extra };
}

export const str = (text, extra = {}) => md(text, { type: 'string', ...extra });
export const int = (text, extra = {}) => md(text, { type: 'integer', ...extra });
export const num = (text, extra = {}) => md(text, { type: 'number', ...extra });
export const bool = (text, extra = {}) => md(text, { type: 'boolean', ...extra });
export const id = (text, extra = {}) => md(text, { type: 'string', pattern: RL, ...extra });
export const idOrTag = (text, extra = {}) => md(text, { ...cref('idOrTag'), ...extra });
export const holderSet = (text) => md(text, cref('holderSet'));
export const text = (t) => md(t, cref('textComponent'));
export const arr = (items, text, extra = {}) => md(text, { type: 'array', items, ...extra });

export function writeSchema(name, schema) {
  const file = path.join(ROOT, 'schemas/minecraft', name);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const out = {
    $schema: 'http://json-schema.org/draft-07/schema#',
    $comment: 'Generated by src/features/schemas/tools/build-schemas.mjs — edit the generator, not this file.',
    ...schema,
  };
  fs.writeFileSync(file, JSON.stringify(out, null, 1) + '\n');
  return file;
}
